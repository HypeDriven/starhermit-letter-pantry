// Writes the engine checks' play scripts (tests/native/*.play) from the
// content: each round is played through the real UI — menus by click, the
// words typed into the letters field (each letter picks the first free
// biscuit showing it) and submitted with Enter — so the scripts follow the
// dictionary-derived targets. Run after changing content.js or the screens:
//   node tools/gen-plays.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { JOURNEY, CHALLENGES, LESSONS } from '../content.js';

const dir = new URL('../tests/native/', import.meta.url);
mkdirSync(dir, { recursive: true });
const out = (name, lines) => writeFileSync(new URL(name, dir), lines.join('\n') + '\n');
const head = (what) => [`# Generated by tools/gen-plays.mjs. ${what}`, 'until 300 =Play', 'frames 20'];
/** Title → Play → a mode card's Start (#n in card order). */
const mode = (n, until) => ['click =Play', 'until 60 Choose a mode', 'frames 10', ...startCard(n), `until 60 ${until}`, 'frames 10'];
/** The n-th mode card's Start: clicked when it shows in the 960 × 540 check, else reached by Tab from the first. */
function startCard(n) {
  if (n <= 4) return [`click =Start #${n}`];
  return [...Array.from({ length: n - 1 }, () => ['key Tab 1', 'frames 4']).flat(), 'key Enter 1'];
}
/** The countdown, then the round's HUD with the letters field focused. */
const roundStart = (targets) => [`until 400 Find all ${targets} target words`, 'frames 20'];
const word = (w) => [`type ${w}`, 'frames 3', 'key Enter 1', 'frames 5'];

// Journey stage 1 (TEA): an invalid word first, Backspace and Escape, then every target typed; the
// results, then Next stage starts stage 2.
{
  const d = JOURNEY[0];
  out('journey-stage-1.play', [
    ...head(`Journey stage 1 (${d.letters.toUpperCase()}): an invalid word, unpick and clear, then ${d.targets.join(', ')} typed; results; Next stage.`),
    ...mode(1, 'stages complete'),
    'click Stage 1: tea',
    ...roundStart(d.targets.length),
    'type ate', 'frames 3', 'key Backspace 1', 'frames 3', 'key Escape 1', 'frames 3',
    // Three letters that are no word: −25, the streak breaks.
    ...word('aet'),
    'expect Moves: 1',
    ...d.targets.flatMap(word),
    'until 200 Pantry stocked',
    'frames 10',
    'expect Journey progress: 1/42',
    'expect First Batch',
    'click =Next stage',
    `until 400 Journey stage 2`,
    'frames 10',
  ]);
}

// A challenge with a move limit (RATION: 8 moves, no undo, no hints): every target typed in order.
{
  const c = CHALLENGES[0];
  out('challenge-ration.play', [
    ...head(`Challenge ${c.id} (${c.letters.toUpperCase()}, ${c.mechanics.moveLimit} moves): ${c.targets.join(', ')} typed.`),
    ...mode(4, 'Challenges'),
    `click ${c.base.toUpperCase()} —`,
    ...roundStart(c.targets.length),
    `expect Moves: 0/${c.mechanics.moveLimit}`,
    ...c.targets.flatMap(word),
    'until 200 Pantry stocked',
    'frames 10',
    'expect Total',
  ]);
}

// Learn: the three lessons, each step performed through the buttons and typing.
{
  const [select, fix, hunt] = LESSONS;
  out('learn.play', [
    ...head('Learn: Picking Biscuits, Second Thoughts and The Full Shelf, every step through the real controls, to their results.'),
    ...mode(5, select.title),
    `click ${select.title}`,
    ...roundStart(select.targets.length),
    'expect Step 1/3',
    'click =Letter T', 'frames 5', 'expect Step 2/3',
    'click =Letter E', 'frames 3', 'click =Letter A', 'frames 3', 'expect Step 3/3',
    'click =Submit', 'frames 5', 'expect Lesson complete! Finish the round',
    ...select.targets.filter((t) => t !== 'tea').flatMap(word),
    'until 200 Pantry stocked', 'frames 10', 'click =Back to title', 'until 60 =Play', 'frames 10',
    ...mode(5, fix.title),
    `click ${fix.title}`,
    ...roundStart(fix.targets.length),
    'click =Letter B', 'frames 3', 'click =Letter B', 'frames 5', 'expect Step 2/4',
    'type re', 'frames 3', 'click =Clear', 'frames 5', 'expect Step 3/4',
    'click =Undo', 'frames 5', 'expect Step 4/4',
    'click =Shuffle', 'frames 5', 'expect Lesson complete! Finish the round',
    ...fix.targets.flatMap(word),
    'until 200 Pantry stocked', 'frames 10', 'click =Back to title', 'until 60 =Play', 'frames 10',
    ...mode(5, hunt.title),
    `click ${hunt.title}`,
    ...roundStart(hunt.targets.length),
    'click =Hint', 'frames 5', 'expect Step 2/3',
    ...word(hunt.bonus[0]), 'expect Bonus words found: 1', 'expect Step 3/3',
    ...hunt.targets.flatMap(word),
    'until 200 Pantry stocked',
    'frames 10',
    'expect Pantry Scholar',
  ]);
}

// Journey stage 2 by keyboard: arrows to the biscuits, Enter picks, Shift+Tab back to the field; the
// tools; pause with Escape on an empty hand; leave, then Resume saved round finishes it.
{
  const d = JOURNEY[1];
  out('keyboard-resume.play', [
    ...head(`Journey stage 2 (${d.letters.toUpperCase()}) after stage 1: biscuits by arrows and Enter, the tools, pause, leave and resume.`),
    ...mode(1, 'stages complete'),
    'click Stage 1: tea',
    ...roundStart(JOURNEY[0].targets.length),
    ...JOURNEY[0].targets.flatMap(word),
    'until 200 Pantry stocked', 'frames 10',
    'click =Next stage',
    ...roundStart(d.targets.length),
    'key ArrowRight 1', 'frames 5', 'key Enter 1', 'frames 5', 'expect Moves: 0',
    'key ArrowRight 1', 'frames 5', 'key Enter 1', 'frames 5',
    'key Backspace 1', 'frames 5',
    'key Escape 1', 'frames 5',
    'click =Shuffle', 'frames 5',
    'click =Hint', 'frames 5',
    'click =Undo', 'frames 5',
    ...word(d.targets[0]),
    'key Escape 1', 'frames 10',
    'until 60 =Resume',
    'click =Leave round',
    'until 60 Resume saved round',
    'frames 10',
    'click =Resume saved round',
    `until 60 Found: ${d.targets[0]}`,
    'frames 20',
    ...d.targets.slice(1).flatMap(word),
    'until 200 Pantry stocked',
    'frames 10',
  ]);
}

// Menus: How to play, Settings (options, themes), the mode lists, the Daily's HUD and its pause dialog.
out('menus.play', [
  ...head('Menus: How to play, Settings (options and a theme), Practice / Challenges / Learn lists, the Daily round, pause overlays.'),
  'click =How to play', 'until 60 Scoring', 'frames 10', 'expect Keyboard', 'click =Back', 'until 60 =Play', 'frames 10',
  'click =Settings', 'until 60 Themes', 'frames 10',
  'click =Left-handed controls', 'frames 3', 'click =Left-handed controls', 'frames 3',
  'click =Berry Cellar', 'frames 5',
  'click =Back', 'until 60 =Play', 'frames 10',
  ...mode(3, 'Pick a difficulty'), 'expect Hard', 'click =Back', 'until 60 Choose a mode', 'frames 10',
  'click =Start #4', 'until 60 Challenges', 'frames 10', 'expect PANTRY —', 'click =Back', 'until 60 Choose a mode', 'frames 10',
  ...startCard(5), 'until 60 Picking Biscuits', 'frames 10', 'click =Back', 'until 60 Choose a mode', 'frames 10',
  'click =Start #2',
  'until 400 Daily Pantry —', 'until 400 target words', 'frames 20',
  'click Pause (', 'until 60 =Resume', 'frames 10',
  'click =Help', 'until 60 Scoring', 'frames 10', 'click =Back', 'until 60 =Resume', 'frames 10',
  'click =Accessibility', 'until 60 Themes', 'frames 10', 'click =Back', 'until 60 =Resume', 'frames 10',
  'click =Resume', 'frames 10', 'expect Submit',
]);
console.log('wrote tests/native/*.play');
